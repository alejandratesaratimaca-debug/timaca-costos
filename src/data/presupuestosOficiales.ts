export const PRESUPUESTOS_MAP: Record<string, PresupuestoProyecto> = {};
PRESUPUESTOS_OFICIALES_TIMACA.forEach(p => {
  if (p.cuentaAuxiliar) {
    PRESUPUESTOS_MAP[p.cuentaAuxiliar] = p;
  }
});

export const getPresupuestoPorCuenta = (cuentaAuxiliar: string): PresupuestoProyecto | undefined => {
  return PRESUPUESTOS_MAP[cuentaAuxiliar];
};

export interface MetricasUsoPresupuesto {
  cuentaAuxiliar: string;
  tienePresupuesto: boolean;
  totalPresupuesto: number;
  totalEjecutado: number;
  saldoDisponible: number;
  porcentajeUso: number;
  oc: string;
  estadoAlerta: 'normal' | 'alerta' | 'critico' | 'excedido' | 'sin_presupuesto';
}

export const calcularUsoPresupuesto = (cuentaAuxiliar: string, totalEjecutado: number): MetricasUsoPresupuesto => {
  const p = getPresupuestoPorCuenta(cuentaAuxiliar);
  const totalPresupuesto = p?.totalPresupuesto || 0;
  const tienePresupuesto = totalPresupuesto > 0;
  const saldoDisponible = totalPresupuesto > 0 ? totalPresupuesto - totalEjecutado : 0;
  const porcentajeUso = totalPresupuesto > 0 ? Math.round((totalEjecutado / totalPresupuesto) * 1000) / 10 : 0;

  let estadoAlerta: MetricasUsoPresupuesto['estadoAlerta'] = 'sin_presupuesto';
  if (tienePresupuesto) {
    if (porcentajeUso > 100) estadoAlerta = 'excedido';
    else if (porcentajeUso >= 85) estadoAlerta = 'critico';
    else if (porcentajeUso >= 70) estadoAlerta = 'alerta';
    else estadoAlerta = 'normal';
  }

  return {
    cuentaAuxiliar,
    tienePresupuesto,
    totalPresupuesto,
    totalEjecutado,
    saldoDisponible,
    porcentajeUso,
    oc: p?.oc || '',
    estadoAlerta
  };
};
